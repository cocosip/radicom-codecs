pub(crate) fn vlc_decode_table(source: &[u16]) -> Vec<u16> {
    let mut table = vec![0u16; 1024];
    for (i, slot) in table.iter_mut().enumerate() {
        let codeword = (i & 0x7F) as u16;
        let context = (i >> 7) as u16;
        let mut offset = 0;
        while offset + 6 < source.len() {
            if source[offset] == context {
                let length = source[offset + 6];
                if source[offset + 5] == (codeword & ((1u16 << length) - 1)) {
                    *slot = (source[offset + 1] << 4)
                        | (source[offset + 2] << 3)
                        | (source[offset + 3] << 12)
                        | (source[offset + 4] << 8)
                        | length;
                }
            }
            offset += 7;
        }
    }
    table
}

pub(crate) const UVLC_DECODE_PREFIXES: [u16; 8] = [
    3 | (5 << 2) | (5 << 5),
    1 | (0 << 2) | (1 << 5),
    2 | (0 << 2) | (2 << 5),
    1 | (0 << 2) | (1 << 5),
    3 | (1 << 2) | (3 << 5),
    1 | (0 << 2) | (1 << 5),
    2 | (0 << 2) | (2 << 5),
    1 | (0 << 2) | (1 << 5),
];

pub(crate) fn uvlc_table_0() -> Vec<u16> {
    let mut table = vec![0u16; 320];
    for (i, slot) in table.iter_mut().enumerate() {
        let mode = i >> 6;
        let mut vlc = i & 0x3F;
        if mode == 0 {
            *slot = 0;
        } else if mode <= 2 {
            let d = UVLC_DECODE_PREFIXES[vlc & 0x7];
            let total_prefix = d & 0x3;
            let total_suffix = (d >> 2) & 0x7;
            let u0_suffix_length = if mode == 1 { total_suffix } else { 0 };
            let u0 = if mode == 1 { d >> 5 } else { 0 };
            let u1 = if mode == 1 { 0 } else { d >> 5 };
            *slot = total_prefix
                | (total_suffix << 3)
                | (u0_suffix_length << 7)
                | (u0 << 10)
                | (u1 << 13);
        } else if mode == 3 {
            let d0 = UVLC_DECODE_PREFIXES[vlc & 0x7];
            vlc >>= d0 & 0x3;
            let d1 = UVLC_DECODE_PREFIXES[vlc & 0x7];
            let (total_prefix, u0_suffix_length, total_suffix, u0, u1) = if (d0 & 0x3) == 3 {
                (
                    (d0 & 0x3) + 1,
                    (d0 >> 2) & 0x7,
                    (d0 >> 2) & 0x7,
                    d0 >> 5,
                    (vlc as u16 & 1) + 1,
                )
            } else {
                (
                    (d0 & 0x3) + (d1 & 0x3),
                    (d0 >> 2) & 0x7,
                    ((d0 >> 2) & 0x7) + ((d1 >> 2) & 0x7),
                    d0 >> 5,
                    d1 >> 5,
                )
            };
            *slot = total_prefix
                | (total_suffix << 3)
                | (u0_suffix_length << 7)
                | (u0 << 10)
                | (u1 << 13);
        } else if mode == 4 {
            let d0 = UVLC_DECODE_PREFIXES[vlc & 0x7];
            vlc >>= d0 & 0x3;
            let d1 = UVLC_DECODE_PREFIXES[vlc & 0x7];
            let total_prefix = (d0 & 0x3) + (d1 & 0x3);
            let u0_suffix_length = (d0 >> 2) & 0x7;
            let total_suffix = u0_suffix_length + ((d1 >> 2) & 0x7);
            let u0 = (d0 >> 5) + 2;
            let u1 = (d1 >> 5) + 2;
            *slot = total_prefix
                | (total_suffix << 3)
                | (u0_suffix_length << 7)
                | (u0 << 10)
                | (u1 << 13);
        }
    }
    table
}

pub(crate) fn uvlc_bias() -> Vec<u8> {
    let mut table = vec![0u8; 320];
    for (i, slot) in table.iter_mut().enumerate() {
        let mode = i >> 6;
        let vlc = i & 0x3F;
        if mode == 3 {
            let d0 = UVLC_DECODE_PREFIXES[vlc & 0x7];
            *slot = if (d0 & 0x3) == 3 { 4 } else { 0 };
        } else if mode == 4 {
            *slot = 10;
        }
    }
    table
}

