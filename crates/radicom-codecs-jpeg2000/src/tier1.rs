//! Classic JPEG 2000 EBCOT Tier-1 coding (ISO/IEC 15444-1 Annex D).
//!
//! The encoder and decoder store flags in four-row stripes and derive MQ
//! contexts from the same significance and sign rules.

use crate::geometry::CodeBlockPass;
use crate::mq::{MqDecoder, MqEncoder};

const FRACTIONAL_BITS: i32 = 6;

/// Weighted-distortion inputs for one code block (OpenJPEG `opj_t1_getwmsedec`):
/// `w1` is the multiple-component-transform norm, `w2` the wavelet norm for the
/// band, and `stepsize` the already gain-adjusted band step size.
#[derive(Debug, Clone, Copy, Default)]
pub(crate) struct PassWeight {
    pub(crate) w1: f64,
    pub(crate) w2: f64,
    pub(crate) stepsize: f64,
}

impl PassWeight {
    /// Weighted MSE decrease of one coding pass, exactly as OpenJPEG accumulates
    /// it (`opj_t1_getwmsedec`): `(w1*w2*step*2^bpno)^2 * nmsedec / 8192`.
    fn wmsedec(&self, nmsedec: i32, bpno: i32) -> f64 {
        let mut wmsedec = self.w1 * self.w2 * self.stepsize * f64::from(1i32 << bpno);
        wmsedec *= wmsedec * f64::from(nmsedec) / 8192.0;
        wmsedec
    }
}

