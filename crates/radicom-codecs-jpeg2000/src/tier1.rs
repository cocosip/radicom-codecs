fn nmsedec_sig(value: u32, bitpos: i32) -> i32 {
    if bitpos > 0 {
        i32::from(LUT_NMSEDEC_SIG[((value >> bitpos) & 0x7F) as usize])
    } else {
        i32::from(LUT_NMSEDEC_SIG0[(value & 0x7F) as usize])
    }
}

const SIG: u32 = 0x0001;
const REFINED: u32 = 0x0002;
const VISITED: u32 = 0x0004;
const SIG_N: u32 = 0x0010;
const SIG_S: u32 = 0x0020;
const SIG_W: u32 = 0x0040;
const SIG_E: u32 = 0x0080;
const SIG_NW: u32 = 0x0100;
const SIG_NE: u32 = 0x0200;
const SIG_SW: u32 = 0x0400;
const SIG_SE: u32 = 0x0800;
const SIG_NEIGHBORS: u32 = SIG_N | SIG_S | SIG_W | SIG_E | SIG_NW | SIG_NE | SIG_SW | SIG_SE;
const SIGN: u32 = 0x1000;
const SIGN_N: u32 = 0x2000;
const SIGN_S: u32 = 0x4000;
const SIGN_W: u32 = 0x8000;
const SIGN_E: u32 = 0x10000;

pub(crate) const CTX_ZC: usize = 0;
pub(crate) const CTX_SIGN: usize = 9;
pub(crate) const CTX_MAG: usize = 14;
pub(crate) const CTX_RUN: usize = 17;
pub(crate) const CTX_UNIFORM: usize = 18;

const ZERO_CONTEXTS: [[u8; 512]; 4] = {
    let mut table = [[0; 512]; 4];
    let mut orientation = 0;
    while orientation < 4 {
        let mut neighbors = 0;
        while neighbors < 512 {
            table[orientation][neighbors] =
                zero_context(stripe_neighbors(neighbors as u32) << 4, orientation as u8) as u8;
            neighbors += 1;
        }
        orientation += 1;
    }
    table
};

const SIGN_CONTEXTS: [(u8, bool); 256] = {
    let mut table = [(0, false); 256];
    let mut index = 0;
    while index < 256 {
        let flags = (((index as u32) & 0xf) << 4) | (((index as u32) >> 4) << 13);
        table[index] = (sign_context(flags) as u8, sign_prediction(flags));
        index += 1;
    }
    table
};

#[derive(Debug, Clone)]
pub(crate) struct EncodedCodeBlock {
    pub(crate) data: Vec<u8>,
    pub(crate) pass_count: u32,
    pub(crate) max_bit_plane: i32,
    pub(crate) passes: Vec<CodeBlockPass>,
}

/// Decodes one code-block from its (already concatenated) coding segments.
pub(crate) fn decode_code_block(
    segments: &[crate::geometry::CodeBlockSegment],
    width: usize,
    height: usize,
    orientation: u8,
    max_bit_plane: i32,
    style: u8,
) -> Result<Vec<i32>, String> {
    if width == 0 || height == 0 {
        return Err("invalid code-block dimensions".into());
    }
    if max_bit_plane < 0 {
        return Ok(vec![0; width * height]);
    }
    // A crafted QCD exponent/guard pair can push the derived bit-plane depth
    // past 30; `1i32 << bit_plane` would then overflow. Valid DICOM precision
    // (<=16 bits) never approaches this, so reject as malformed instead.
    if max_bit_plane >= 31 {
        return Err(format!(
            "code-block bit-plane depth {max_bit_plane} exceeds the supported 30-bit limit"
        ));
    }
    let mut decoder = Tier1Decoder::new(width, height, orientation, style);
    decoder.run(segments, max_bit_plane)?;
    Ok(decoder.finish())
}

// One word tracks a four-sample column of a stripe. Bits 0..18 store a
// 3-column by 6-row significance grid in row-major order, with one border row
// above and below. The four interior center bits are the samples themselves.
// Visited and refined flags mirror those center bits 14 and 15 bits higher.
const STRIPE_SIG: u32 = 0b10010010010000;
const STRIPE_VIS: u32 = STRIPE_SIG << 14;
const NEIGHBORS: u32 = 0x1ef;

const fn stripe_cardinal(flags: u32) -> u32 {
    ((flags >> 1) & 1) | ((flags >> 6) & 2) | ((flags >> 1) & 4) | ((flags >> 2) & 8)
}

const fn stripe_neighbors(flags: u32) -> u32 {
    stripe_cardinal(flags)
        | ((flags & 1) << 4)
        | ((flags & 4) << 3)
        | (flags & 0x40)
        | ((flags >> 1) & 0x80)
}

pub(crate) struct Tier1Encoder {
    width: usize,
    height: usize,
    stride: usize,
    data: Vec<[i32; 4]>,
    flags: Vec<u32>,
    zero_contexts: &'static [u8; 512],
    style: u8,
    mq: MqEncoder,
    bit_plane: i32,
    nmsedec: i32,
}

impl Tier1Encoder {
    pub(crate) fn new() -> Self {
        Self {
            width: 0,
            height: 0,
            stride: 0,
            data: Vec::new(),
            flags: Vec::new(),
            zero_contexts: &ZERO_CONTEXTS[0],
            style: 0,
            mq: MqEncoder::new(),
            bit_plane: 0,
            nmsedec: 0,
        }
    }

    /// Coefficients are in the reference fixed-point domain with six
    /// fractional bits.
    pub(crate) fn encode(
        &mut self,
        coefficients: &[i32],
        (width, height): (usize, usize),
        orientation: u8,
        style: u8,
        weight: &PassWeight,
    ) -> Result<EncodedCodeBlock, String> {
        if width == 0 || height == 0 || coefficients.len() != width * height {
            return Err("invalid code-block dimensions".into());
        }
        let max = coefficients
            .iter()
            .map(|v| v.unsigned_abs())
            .max()
            .unwrap_or(0);
        let max_bit_plane = 31 - max.leading_zeros() as i32;
        let bit_count = max_bit_plane - (FRACTIONAL_BITS - 1);
        if bit_count <= 0 {
            return Ok(EncodedCodeBlock {
                data: Vec::new(),
                pass_count: 0,
                max_bit_plane,
                passes: Vec::new(),
            });
        }

        self.width = width;
        self.height = height;
        self.stride = width + 2;
        self.zero_contexts = &ZERO_CONTEXTS[usize::from(orientation)];
        self.style = style;
        self.bit_plane = max_bit_plane;
        let padded_len = self.stride * (height.div_ceil(4) + 2);
        self.data.resize(padded_len, [0; 4]);
        self.flags.resize(padded_len, 0);
        self.flags.fill(0);
        for (stripe, source) in coefficients.chunks(width * 4).enumerate() {
            let first = self.index(0, stripe);
            let destination = &mut self.data[first..first + width];
            for (row, source) in source.chunks_exact(width).enumerate() {
                for (column, &value) in destination.iter_mut().zip(source) {
                    column[row] = value;
                }
            }
        }
        self.mq.restart(coefficients.len() * bit_count as usize / 8);
        let pass_count = (bit_count * 3 - 2) as u32;
        let (data, passes) = self.run(pass_count as i32, weight);
        Ok(EncodedCodeBlock {
            data,
            pass_count,
            max_bit_plane,
            passes,
        })
    }

    fn index(&self, x: usize, y: usize) -> usize {
        (y + 1) * self.stride + (x + 1)
    }

    fn run(&mut self, pass_count: i32, weight: &PassWeight) -> (Vec<u8>, Vec<CodeBlockPass>) {
        let mut passes = Vec::with_capacity(pass_count as usize);
        let mut cumulative_distortion = 0.0f64;
        let mut pass = 0;
        let mut pass_type = 2;
        while self.bit_plane >= 0 && pass < pass_count {
            self.nmsedec = 0;
            match pass_type {
                0 => self.encode_sigpass(),
                1 => self.encode_refpass(),
                _ => self.encode_cleanup(),
            }
            if self.style & 0x02 != 0 {
                self.mq.reset_contexts();
            }
            // OpenJPEG scores the pass after it has been coded, using the
            // unshifted bit-plane index (`bpno`).
            let bpno = self.bit_plane - FRACTIONAL_BITS;
            cumulative_distortion += weight.wmsedec(self.nmsedec, bpno);
            let last = pass + 1 == pass_count;
            passes.push(CodeBlockPass {
                rate: if last {
                    0
                } else {
                    self.mq.numbytes().wrapping_add(3)
                },
                distortiondec: cumulative_distortion,
                term: last,
            });
            pass += 1;
            if pass_type == 2 {
                pass_type = 0;
                self.bit_plane -= 1;
            } else {
                pass_type += 1;
            }
        }
        let data = self.mq.flush();
        // The terminated final pass reports the flushed byte count; every
        // earlier pass keeps its +3 MQ margin.
        if let Some(last) = passes.last_mut() {
            last.rate = data.len() as u32;
        }
        if !passes.is_empty() {
            // Make sure pass rates are increasing (OpenJPEG clamps from the end).
            let mut last_pass_rate = data.len() as u32;
            for entry in passes.iter_mut().rev() {
                if entry.rate > last_pass_rate {
                    entry.rate = last_pass_rate;
                } else {
                    last_pass_rate = entry.rate;
                }
            }
            // A pass may not end with 0xFF; that byte belongs to the next pass.
            for entry in passes.iter_mut() {
                let index = entry.rate.saturating_sub(1) as usize;
                if entry.rate > 0 && data.get(index) == Some(&0xFF) {
                    entry.rate -= 1;
                }
            }
        }
        (data, passes)
    }

    fn encode_sigpass(&mut self) {
        for stripe in 0..self.height.div_ceil(4) {
            let rows = (self.height - stripe * 4).min(4);
            let first = self.index(0, stripe);
            if rows == 4 {
                for index in first..first + self.width {
                    if self.flags[index] == 0 {
                        continue;
                    }
                    self.sig_sample(index, 0);
                    self.sig_sample(index, 1);
                    self.sig_sample(index, 2);
                    self.sig_sample(index, 3);
                }
            } else {
                for index in first..first + self.width {
                    for row in 0..rows {
                        self.sig_sample(index, row);
                    }
                }
            }
        }
    }

    #[inline(always)]
    fn sig_sample(&mut self, index: usize, row: usize) {
        let shift = row * 3;
        let neighbors = self.flags[index] >> shift;
        if neighbors & 0x10 != 0 || neighbors & NEIGHBORS == 0 {
            return;
        }
        let significant = self.magnitude_bit(index, row);
        self.mq.encode(
            significant,
            usize::from(self.zero_contexts[(neighbors & 511) as usize]),
        );
        self.flags[index] |= 1 << (18 + shift);
        if significant {
            self.set_significant(index, row, false);
        }
    }

    fn encode_refpass(&mut self) {
        let bpno = self.bit_plane - FRACTIONAL_BITS;
        let nmsedec = if bpno == 0 {
            &LUT_NMSEDEC_REF0
        } else {
            &LUT_NMSEDEC_REF
        };
        let shift = self.bit_plane;
        let end = self.index(0, self.height.div_ceil(4)) - self.stride + self.width;
        let first = self.index(0, 0);
        for (flags, data) in self.flags[first..end]
            .iter_mut()
            .zip(&self.data[first..end])
        {
            let mut candidates = *flags & !(*flags >> 14) & STRIPE_SIG;
            if candidates == 0 {
                continue;
            }
            let refined = candidates << 15;
            while candidates != 0 {
                let row = (candidates.trailing_zeros() - 4) as usize / 3;
                candidates &= candidates - 1;
                let value = data[row].unsigned_abs();
                let row_flags = *flags >> (row * 3);
                let context = if row_flags & (1 << 19) != 0 {
                    CTX_MAG + 2
                } else {
                    CTX_MAG + usize::from(row_flags & NEIGHBORS != 0)
                };
                self.nmsedec += i32::from(nmsedec[((value >> bpno) & 127) as usize]);
                self.mq.encode(value & (1 << shift) != 0, context);
            }
            *flags |= refined;
        }
    }

    fn encode_cleanup(&mut self) {
        for stripe in 0..self.height.div_ceil(4) {
            let rows = (self.height - stripe * 4).min(4);
            let valid = STRIPE_SIG & ((1 << (rows * 3 + 2)) - 1);
            let full = rows == 4;
            let first = self.index(0, stripe);
            for index in first..first + self.width {
                let flags = self.flags[index];
                let mut candidates = !(flags | (flags >> 14)) & valid;
                if candidates == 0 {
                    self.flags[index] = flags & !STRIPE_VIS;
                    continue;
                }
                if full && flags == 0 {
                    let column = self.data[index];
                    let run = column
                        .iter()
                        .position(|v| v.unsigned_abs() & (1 << self.bit_plane) != 0);
                    self.mq.encode(run.is_some(), CTX_RUN);
                    let Some(row) = run else {
                        continue;
                    };
                    self.mq.encode(row & 2 != 0, CTX_UNIFORM);
                    self.mq.encode(row & 1 != 0, CTX_UNIFORM);
                    self.set_significant(index, row, self.style & 0x20 != 0);
                    candidates &= valid << ((row + 1) * 3);
                }
                while candidates != 0 {
                    let offset = candidates.trailing_zeros() as usize - 4;
                    let row = offset / 3;
                    candidates &= candidates - 1;
                    let significant = self.magnitude_bit(index, row);
                    let pattern = ((self.flags[index] >> offset) & 511) as usize;
                    self.mq
                        .encode(significant, usize::from(self.zero_contexts[pattern]));
                    if significant {
                        self.set_significant(index, row, self.style & 0x20 != 0);
                    }
                }
                self.flags[index] &= !STRIPE_VIS;
            }
        }
    }

    fn set_significant(&mut self, index: usize, row: usize, uniform_sign: bool) {
        let data = self.data[index][row];
        self.nmsedec += nmsedec_sig(data.unsigned_abs(), self.bit_plane - FRACTIONAL_BITS);
        let negative = data < 0;
        let shift = row * 3;
        let flags = self.flags[index] >> shift;
        if uniform_sign {
            self.mq.encode(negative, CTX_UNIFORM);
        } else {
            let significance = stripe_cardinal(flags);
            let north = if row == 0 {
                self.data[index - self.stride][3]
            } else {
                self.data[index][row - 1]
            };
            let south = if row == 3 {
                self.data[index + self.stride][0]
            } else {
                self.data[index][row + 1]
            };
            let signs = u32::from(north < 0)
                | (u32::from(south < 0) << 1)
                | (u32::from(self.data[index - 1][row] < 0) << 2)
                | (u32::from(self.data[index + 1][row] < 0) << 3);
            let key = significance | ((signs & significance) << 4);
            let (context, prediction) = SIGN_CONTEXTS[key as usize];
            self.mq.encode(negative ^ prediction, usize::from(context));
        }
        self.flags[index] |= 0x10 << shift;
        self.flags[index - 1] |= 0x20 << shift;
        self.flags[index + 1] |= 0x08 << shift;
        if row == 0 && self.style & 0x08 == 0 {
            let north = index - self.stride;
            self.flags[north - 1] |= 1 << 17;
            self.flags[north] |= 1 << 16;
            self.flags[north + 1] |= 1 << 15;
        }
        if row == 3 {
            let south = index + self.stride;
            self.flags[south - 1] |= 4;
            self.flags[south] |= 2;
            self.flags[south + 1] |= 1;
        }
    }

    fn magnitude_bit(&self, index: usize, row: usize) -> bool {
        self.data[index][row].unsigned_abs() & (1 << self.bit_plane) != 0
    }
}

struct Tier1Decoder {
    width: usize,
    height: usize,
    stride: usize,
    data: Vec<i32>,
    flags: Vec<u32>,
    orientation: u8,
    style: u8,
    bit_plane: i32,
    in_cleanup: bool,
}

impl Tier1Decoder {
    fn new(width: usize, height: usize, orientation: u8, style: u8) -> Self {
        Self {
            width,
            height,
            stride: width + 2,
            data: vec![0; (width + 2) * (height + 2)],
            flags: vec![0; (width + 2) * (height + 2)],
            orientation,
            style,
            bit_plane: 0,
            in_cleanup: false,
        }
    }

    fn index(&self, x: usize, y: usize) -> usize {
        (y + 1) * self.stride + (x + 1)
    }

    fn index_i(&self, x: i32, y: i32) -> usize {
        ((y + 1) as usize) * self.stride + (x + 1) as usize
    }

    fn run(
        &mut self,
        segments: &[crate::geometry::CodeBlockSegment],
        max_bit_plane: i32,
    ) -> Result<(), String> {
        self.bit_plane = max_bit_plane;
        let mut bytes = Vec::new();
        let mut total_passes = 0u32;
        for segment in segments {
            if segment.pass_count == 0 {
                continue;
            }
            bytes.extend_from_slice(&segment.data);
            total_passes += segment.pass_count;
        }
        if total_passes == 0 {
            return Ok(());
        }
        let mut mq = MqDecoder::new(&bytes);
        let mut raw = RawBitReader::new(&bytes);
        let mut pass_type = 2;
        for pass in 0..total_passes {
            if self.bit_plane < 0 {
                break;
            }
            if pass_type == 0 || (pass_type == 2 && pass == 0) {
                for flag in &mut self.flags {
                    *flag &= !VISITED;
                }
            }
            let lazy = self.is_lazy_pass(max_bit_plane, pass_type);
            match pass_type {
                0 => self.decode_sigpass(&mut mq, &mut raw, lazy),
                1 => self.decode_refpass(&mut mq, &mut raw, lazy),
                _ => {
                    self.in_cleanup = true;
                    self.decode_cleanup(&mut mq)?;
                    self.in_cleanup = false;
                }
            }
            if self.style & 0x02 != 0 && !lazy {
                mq.contexts_mut().reset();
            }
            if pass_type == 2 {
                pass_type = 0;
                self.bit_plane -= 1;
            } else {
                pass_type += 1;
            }
        }
        Ok(())
    }

    fn is_lazy_pass(&self, max_bit_plane: i32, pass_type: i32) -> bool {
        if self.style & 0x01 == 0 {
            return false;
        }
        let pass_index_from_msb = (max_bit_plane - self.bit_plane) * 3 + pass_type;
        pass_index_from_msb >= 10 && pass_type != 2
    }

    fn decode_sigpass(&mut self, mq: &mut MqDecoder<'_>, raw: &mut RawBitReader<'_>, lazy: bool) {
        for stripe in (0..self.height).step_by(4) {
            for x in 0..self.width {
                for dy in 0..4 {
                    let y = stripe + dy;
                    if y >= self.height {
                        break;
                    }
                    let index = self.index(x, y);
                    let flags = self.flags[index];
                    if flags & SIG != 0 || flags & SIG_NEIGHBORS == 0 {
                        continue;
                    }
                    let bit = if lazy {
                        raw.read_bit()
                    } else {
                        mq.decode(zero_context(flags, self.orientation))
                    };
                    self.flags[index] |= VISITED;
                    if bit {
                        if lazy {
                            self.set_significant_raw(x, y, index, raw);
                        } else {
                            self.set_significant_mq(x, y, index, mq);
                        }
                    }
                }
            }
        }
    }

    fn decode_refpass(&mut self, mq: &mut MqDecoder<'_>, raw: &mut RawBitReader<'_>, lazy: bool) {
        for stripe in (0..self.height).step_by(4) {
            for x in 0..self.width {
                for dy in 0..4 {
                    let y = stripe + dy;
                    if y >= self.height {
                        break;
                    }
                    let index = self.index(x, y);
                    let flags = self.flags[index];
                    if flags & SIG == 0 || flags & VISITED != 0 {
                        continue;
                    }
                    let bit = if lazy {
                        raw.read_bit()
                    } else {
                        mq.decode(magnitude_context(flags))
                    };
                    let half = (1i32 << self.bit_plane) >> 1;
                    if self.data[index] < 0 {
                        self.data[index] += if bit { -half } else { half };
                    } else {
                        self.data[index] += if bit { half } else { -half };
                    }
                    self.flags[index] |= REFINED;
                }
            }
        }
    }

    fn decode_cleanup(&mut self, mq: &mut MqDecoder<'_>) -> Result<(), String> {
        for stripe in (0..self.height).step_by(4) {
            for x in 0..self.width {
                let mut can_run_length = stripe + 3 < self.height;
                if can_run_length {
                    for dy in 0..4 {
                        let flags = self.flags[self.index(x, stripe + dy)];
                        if flags & (VISITED | SIG | SIG_NEIGHBORS) != 0 {
                            can_run_length = false;
                            break;
                        }
                    }
                }
                if can_run_length && !mq.decode(CTX_RUN) {
                    continue;
                }
                let run_length = if can_run_length {
                    (i32::from(mq.decode(CTX_UNIFORM)) << 1) | i32::from(mq.decode(CTX_UNIFORM))
                } else {
                    -1
                };
                for dy in 0..4 {
                    let y = stripe + dy;
                    if y >= self.height {
                        break;
                    }
                    if can_run_length && (dy as i32) < run_length {
                        continue;
                    }
                    let index = self.index(x, y);
                    let flags = self.flags[index];
                    if flags & VISITED != 0 || flags & SIG != 0 {
                        self.flags[index] &= !VISITED;
                        continue;
                    }
                    let significant = if can_run_length && dy as i32 == run_length {
                        true
                    } else {
                        mq.decode(zero_context(flags, self.orientation))
                    };
                    if significant {
                        self.set_significant_mq(x, y, index, mq);
                    }
                    self.flags[index] &= !VISITED;
                }
            }
        }
        Ok(())
    }

    fn set_significant_mq(&mut self, x: usize, y: usize, index: usize, mq: &mut MqDecoder<'_>) {
        if self.style & 0x20 != 0 && self.in_cleanup {
            // SEGSYM: signs of coefficients that become significant in the
            // cleanup pass are coded with the uniform context.
            let sign_bit = mq.decode(CTX_UNIFORM);
            self.set_significant_value(x, y, index, sign_bit);
            return;
        }
        let sign_bit =
            mq.decode(sign_context(self.flags[index])) ^ sign_prediction(self.flags[index]);
        self.set_significant_value(x, y, index, sign_bit);
    }

    fn set_significant_raw(
        &mut self,
        x: usize,
        y: usize,
        index: usize,
        raw: &mut RawBitReader<'_>,
    ) {
        let sign_bit = raw.read_bit();
        self.set_significant_value(x, y, index, sign_bit);
    }

    fn set_significant_value(&mut self, x: usize, y: usize, index: usize, sign_bit: bool) {
        let one = 1i32 << self.bit_plane;
        let value = one | (one >> 1);
        self.data[index] = if sign_bit { -value } else { value };
        if sign_bit {
            self.flags[index] |= SIGN;
        }
        self.flags[index] |= SIG;
        self.update_neighbors(x, y);
    }

    fn update_neighbors(&mut self, x: usize, y: usize) {
        let negative = self.flags[self.index(x, y)] & SIGN != 0;
        if !(self.style & 0x08 != 0 && y & 3 == 0) {
            self.mark(x as i32, y as i32 - 1, SIG_S, negative, SIGN_S);
            let idx_nw = self.index_i(x as i32 - 1, y as i32 - 1);
            let idx_ne = self.index_i(x as i32 + 1, y as i32 - 1);
            self.flags[idx_nw] |= SIG_SE;
            self.flags[idx_ne] |= SIG_SW;
        }
        self.mark(x as i32, y as i32 + 1, SIG_N, negative, SIGN_N);
        self.mark(x as i32 - 1, y as i32, SIG_E, negative, SIGN_E);
        self.mark(x as i32 + 1, y as i32, SIG_W, negative, SIGN_W);
        let idx_sw = self.index_i(x as i32 - 1, y as i32 + 1);
        let idx_se = self.index_i(x as i32 + 1, y as i32 + 1);
        self.flags[idx_sw] |= SIG_NE;
        self.flags[idx_se] |= SIG_NW;
    }

    fn mark(&mut self, x: i32, y: i32, sig_flag: u32, negative: bool, sign_flag: u32) {
        let index = self.index_i(x, y);
        self.flags[index] |= sig_flag;
        if negative {
            self.flags[index] |= sign_flag;
        }
    }

    fn finish(self) -> Vec<i32> {
        let mut result = vec![0i32; self.width * self.height];
        for y in 0..self.height {
            for x in 0..self.width {
                let value = self.data[self.index(x, y)];
                result[y * self.width + x] = if value >= 0 {
                    value >> FRACTIONAL_BITS
                } else {
                    -((-value) >> FRACTIONAL_BITS)
                };
            }
        }
        result
    }
}

struct RawBitReader<'a> {
    data: &'a [u8],
    position: usize,
    buffer: u32,
    bit_count: i32,
}

impl<'a> RawBitReader<'a> {
    fn new(data: &'a [u8]) -> Self {
        Self {
            data,
            position: 0,
            buffer: 0,
            bit_count: 0,
        }
    }

    fn read_bit(&mut self) -> bool {
        if self.bit_count == 0 {
            if self.buffer == 0xFF {
                let next = self.read_byte();
                if next > 0x8F {
                    self.buffer = 0xFF;
                    self.bit_count = 8;
                } else {
                    self.buffer = u32::from(next);
                    self.bit_count = 7;
                }
            } else {
                self.buffer = u32::from(self.read_byte());
                self.bit_count = 8;
            }
        }
        self.bit_count -= 1;
        (self.buffer >> self.bit_count) & 1 != 0
    }

    fn read_byte(&mut self) -> u8 {
        let byte = self.data.get(self.position).copied().unwrap_or(0xFF);
        self.position += 1;
        byte
    }
}

const fn zero_context(flags: u32, orientation: u8) -> usize {
    let horizontal = (flags & (SIG_W | SIG_E)).count_ones();
    let vertical = (flags & (SIG_N | SIG_S)).count_ones();
    let diagonal = (flags & (SIG_NW | SIG_NE | SIG_SW | SIG_SE)).count_ones();
    let (horizontal, vertical) = if orientation == 1 {
        (vertical, horizontal)
    } else {
        (horizontal, vertical)
    };
    let n = if orientation == 3 {
        let hv = horizontal + vertical;
        match diagonal {
            0 => match hv {
                0 => 0,
                1 => 1,
                _ => 2,
            },
            1 => match hv {
                0 => 3,
                1 => 4,
                _ => 5,
            },
            2 => {
                if hv == 0 {
                    6
                } else {
                    7
                }
            }
            _ => 8,
        }
    } else {
        match horizontal {
            0 => match vertical {
                0 => match diagonal {
                    0 => 0,
                    1 => 1,
                    _ => 2,
                },
                1 => 3,
                _ => 4,
            },
            1 => match vertical {
                0 => {
                    if diagonal == 0 {
                        5
                    } else {
                        6
                    }
                }
                _ => 7,
            },
            _ => 8,
        }
    };
    CTX_ZC + n
}

const fn sign_context(flags: u32) -> usize {
    let (mut horizontal, mut vertical) = sign_contributions(flags);
    if horizontal < 0 {
        horizontal = -horizontal;
        vertical = -vertical;
    }
    let n = if horizontal == 0 {
        if vertical == 0 {
            0
        } else {
            1
        }
    } else {
        match vertical {
            -1 => 2,
            0 => 3,
            _ => 4,
        }
    };
    CTX_SIGN + n
}

const fn sign_prediction(flags: u32) -> bool {
    let (horizontal, vertical) = sign_contributions(flags);
    horizontal < 0 || (horizontal == 0 && vertical < 0)
}

const fn sign_contributions(flags: u32) -> (i32, i32) {
    // In both nibbles the cardinal neighbors are ordered N, S, W, E.
    let significant = (flags >> 4) & 0xf;
    let negative = significant & (flags >> 13);
    let positive = significant & !negative;
    (
        (positive & 0xc != 0) as i32 - (negative & 0xc != 0) as i32,
        (positive & 0x3 != 0) as i32 - (negative & 0x3 != 0) as i32,
    )
}

fn magnitude_context(flags: u32) -> usize {
    if flags & REFINED != 0 {
        CTX_MAG + 2
    } else if flags & SIG_NEIGHBORS != 0 {
        CTX_MAG + 1
    } else {
        CTX_MAG
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn pattern(width: usize, height: usize) -> Vec<i32> {
        (0..width * height)
            .map(|i| ((i * 37 + i * i * 11) % 200) as i32 - 100)
            .collect()
    }

    #[test]
    fn round_trips_code_blocks_exactly() {
        for (width, height, orientation) in [
            (1, 1, 0),
            (1, 17, 1),
            (17, 1, 2),
            (11, 6, 0),
            (11, 7, 1),
            (13, 9, 3),
            (32, 24, 1),
            (64, 64, 3),
        ] {
            let values = pattern(width, height);
            let coefficients: Vec<i32> = values.iter().map(|v| v * 64).collect();
            let encoded = Tier1Encoder::new()
                .encode(
                    &coefficients,
                    (width, height),
                    orientation,
                    0,
                    &PassWeight::default(),
                )
                .unwrap();
            let segment = crate::geometry::CodeBlockSegment {
                data: encoded.data.clone(),
                pass_count: encoded.pass_count,
            };
            let decoded = decode_code_block(
                &[segment],
                width,
                height,
                orientation,
                encoded.max_bit_plane,
                0,
            )
            .unwrap();
            assert_eq!(decoded, values, "{width}x{height} orient={orientation}");
        }
    }

    #[test]
    fn all_zero_block_has_no_passes() {
        let encoded = Tier1Encoder::new()
            .encode(&[0i32; 16], (4, 4), 0, 0, &PassWeight::default())
            .unwrap();
        assert_eq!(encoded.pass_count, 0);
        assert!(encoded.data.is_empty());
    }

    #[test]
    fn encoder_reuse_preserves_bytes_across_block_shapes_and_styles() {
        let weight = PassWeight {
            w1: 1.0,
            w2: 1.0,
            stepsize: 1.0,
        };
        let mut reused = Tier1Encoder::new();
        for (width, height, orientation, style) in [
            (64, 64, 0, 0),
            (5, 9, 3, 0x08),
            (1, 2, 2, 0x02),
            (64, 64, 1, 0),
        ] {
            let coefficients: Vec<_> = pattern(width, height).into_iter().map(|v| v * 64).collect();
            let args = (width, height);
            let expected = Tier1Encoder::new()
                .encode(&coefficients, args, orientation, style, &weight)
                .unwrap();
            let observed = reused
                .encode(&coefficients, args, orientation, style, &weight)
                .unwrap();
            assert_eq!(observed.data, expected.data);
            assert_eq!(observed.max_bit_plane, expected.max_bit_plane);
            assert_eq!(observed.pass_count, expected.pass_count);
            for (observed, expected) in observed.passes.iter().zip(&expected.passes) {
                assert_eq!(observed.rate, expected.rate);
                assert_eq!(
                    observed.distortiondec.to_bits(),
                    expected.distortiondec.to_bits()
                );
                assert_eq!(observed.term, expected.term);
            }
        }
    }

    #[test]
    fn reset_vertical_causal_and_sign_segment_styles_round_trip() {
        for style in [0x02u8, 0x08, 0x20, 0x02 | 0x20] {
            for (width, height, orientation) in [(13, 9, 3), (32, 24, 1), (17, 17, 0)] {
                let values = pattern(width, height);
                let coefficients: Vec<i32> = values.iter().map(|v| v * 64).collect();
                let encoded = Tier1Encoder::new()
                    .encode(
                        &coefficients,
                        (width, height),
                        orientation,
                        style,
                        &PassWeight::default(),
                    )
                    .unwrap();
                let segment = crate::geometry::CodeBlockSegment {
                    data: encoded.data.clone(),
                    pass_count: encoded.pass_count,
                };
                let decoded = decode_code_block(
                    &[segment],
                    width,
                    height,
                    orientation,
                    encoded.max_bit_plane,
                    style,
                )
                .unwrap();
                assert_eq!(
                    decoded, values,
                    "style=0x{style:02X} {width}x{height} orient={orientation}"
                );
            }
        }
    }

    #[test]
    fn context_derivation_matches_known_shapes() {
        assert_eq!(zero_context(0, 0), 0);
        assert_eq!(zero_context(SIG_E, 0), 5);
        assert_eq!(zero_context(SIG_N, 0), 3);
        assert_eq!(zero_context(SIG_N | SIG_S | SIG_E | SIG_W, 3), 2);
        assert_eq!(zero_context(SIG_N | SIG_S | SIG_E | SIG_W | SIG_NW, 3), 5);
        assert_eq!(sign_context(0), 9);
        assert!(sign_prediction(SIG_W | SIGN_W));
    }
}
